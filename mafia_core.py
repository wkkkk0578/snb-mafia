    def on_vote(self):
        g = self.g
        dur = g._dur("vote")
        if g.stylist:
            idx = list(g.brains).index(self.id)
            g.schedule(1.5 + idx * 1.1 + self.rng.uniform(0, 1.5),        # 요청을 몇 초에 걸쳐 나눠 보냄
                       lambda: g.phase == "vote" and self.p.alive and self.id not in g.votes
                       and g.decide(self.id, "vote_decide", cands=g.targets(self.id), fallback=self._cast, wait=8))
            g.schedule(dur - 2.5, lambda: g.phase == "vote" and self.id not in g.votes and self._cast())
        else:
            g.schedule(self.rng.uniform(3, min(14, dur - 2)), self._cast)

    def _cast(self):
        g = self.g
        if g.phase != "vote" or not self.p.alive or self.id in g.votes:
            return
        lv = self.llm_vote                                  # 토론 중에 말한 투표 의향이 있으면 그대로
        if lv and lv[0] == g.day:
            if lv[1] == "abstain":
                g.vote(self.id, None)
                return
            if lv[1] in g.targets(self.id) and not (self.mafia_side and lv[1] in self.team()):
                g.vote(self.id, lv[1])
                return
        t = self.top()
        sc = self.score(t) if t else -999
        if t is not None and not self.mafia_side and self.conf(t) < 1.3:
            # 확신 없음 → 반은 기권, 반은 남 말 말고 내 의심(sus)대로
            if self.rng.random() < .5:
                g.vote(self.id, None)
                if self.rng.random() < .25:
                    g.ai_line(self.id, "quiet")
                return
            own = [c for c in self.others() if self.truth.get(c) not in ("town?",) and self.truth.get(c) not in ROLE_INFO
                   or self.truth.get(c) in MAFIA_TEAM]
            t = max(own or self.others(), key=lambda c: self.sus.get(c, 0) + self.rng.uniform(0, .8))
        elif self.mafia_side and t is not None and g.heat[t] < 1.0:
            t = self.rng.choice([c for c in self.others() if c not in self.team()] or [t])   # 묻어가기: 흐름 없으면 아무나
        if t is None or sc < -500:
            g.vote(self.id, None)
            return
        g.vote(self.id, t)
        if self.rng.random() < .2:
            g.ai_line(self.id, "vote", x=t)

