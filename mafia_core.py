def pick_chars(count, chars, used=(), rng=None):
    """캐릭터 랜덤 배정: 안 쓴 캐릭터부터, 모자라면 겹쳐서."""
    rng = rng or random.Random()
    chars = list(chars or [])
    if not chars:
        return [None] * count
    out, pool = [], [c for c in chars if c not in used]
    for _ in range(count):
        if not pool:
            pool = list(chars)
        c = rng.choice(pool)
        pool.remove(c)
        out.append(c)
    return out


