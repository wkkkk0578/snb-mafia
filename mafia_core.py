    def _bomb_plan(self, now):
        """낮이 시작될 때: 둘째 날부터, 5인 이상, 하루 40%, 판당 최대 2번."""
        if not self.bomb_on or self.bomb_n >= 2:
            return
        force = self.test.get("bomb_force")
        if not force and (self.day < 2 or len(self.order) < 5 or self.rng.random() >= .4):
            return
        at = self.rng.uniform(6, 14) if force else self.rng.uniform(10, 35)
        self.schedule(at, self._bomb_arrive)

    def _bomb_arrive(self):
        if self.phase != "day" or self.bomb or self.roulette:
            return
        left = self.deadline - self.now - 5
        fuse = min(self.rng.uniform(20, 45), left)
        if fuse < 12:
            return
        cands = [p.id for p in self.alive_list() if p.id not in self.jailed]
        if len(cands) < 3:
            return
        holder = self.rng.choice(cands)
        self.bomb_n += 1
        self.bomb = dict(holder=holder, giver=None, t0=self.now, end=self.now + fuse, got=self.now, n=0)
        self.version += 1
        self._event("arrive", who=holder)
        self.sys(f"💣 폭탄 도착! {self.name(holder)}님이 폭탄을 들었어요. 터지기 전에 다른 사람에게 건네세요! "
                 "(← → 로 다가가서 ↓ 로 건네기)")
        self._bomb_got(holder, None)

    def _bomb_got(self, pid, giver):
        b = self.brains.get(pid)
        if b:
            b.on_bomb_got(giver)
        if giver and giver in self.brains:
            gb = self.brains[giver]
            self.schedule(self.rng.uniform(.6, 1.4), lambda: self.ai_line(giver, "ev_passed", x=pid, wait=1.5,
                                                                            q=f"방금 {self.name(pid)}에게 폭탄을 넘김"))
            self.ai_moves.pop(giver, None)

    def bomb_view(self, now):
        b = self.bomb
        if not b:
            return None
        prog = (now - b["t0"]) / max(1, b["end"] - b["t0"])      # 남은 시간 숫자는 안 보냄 — 불꽃 속도만
        return dict(holder=b["holder"], giver=b["giver"], fz=round(min(1, max(0, prog)), 2),
                    cool=round(max(0, b["got"] + 1.5 - now), 1))

    def update_pos(self, pos, reach=None):
        """방장 화면의 캐릭터 위치(px) — 건넬 수 있는 거리 판정에 씀."""
        self.pos = dict(pos)
        if reach:
            self.reach = reach

    def dist(self, a, b):
        if a not in self.pos or b not in self.pos:
            return 9e9
        return abs(self.pos[a] - self.pos[b])

    def bomb_targets(self, pid):
        b = self.bomb
        if not b or b["holder"] != pid:
            return []
        return [p.id for p in self.alive_list() if p.id != pid and p.id not in self.jailed and p.id != b["giver"]]

    def bomb_pass(self, pid, target=None, slack=1.35):
        """건네기: 방장이 최신 위치로 거리 확인. target 이 없으면 가장 가까운 사람."""
        b = self.bomb
        if self.phase != "day" or not b or b["holder"] != pid:
            return False
        if self.now - b["got"] < 1.5:
            return False                                         # 받은 직후 1.5초는 못 넘김
        cands = self.bomb_targets(pid)
        if target is None or target not in cands:
            near = sorted(cands, key=lambda c: self.dist(pid, c))
            target = near[0] if near else None
        if target is None or self.dist(pid, target) > self.reach * slack:
            return False
        b.update(holder=target, giver=pid, got=self.now, n=b["n"] + 1)
        self.version += 1
        self._event("pass", who=target, frm=pid)
        self.sys(f"💣 {self.name(pid)} → {self.name(target)}")
        self.ai_moves.pop(pid, None)
        self._bomb_got(target, pid)
        return True

    def bomb_drop(self, pid):
        """폭탄 든 사람 접속 끊김 → 가장 가까운 사람에게 자동으로."""
        b = self.bomb
        if b and b["holder"] == pid:
            cands = [p.id for p in self.alive_list() if p.id != pid and p.id not in self.jailed]
            if cands:
                t = min(cands, key=lambda c: self.dist(pid, c))
                b.update(holder=t, giver=None, got=self.now, n=b["n"] + 1)
                self._event("pass", who=t, frm=pid)
                self.sys(f"💣 {self.name(pid)}님 연결이 끊겨 {self.name(t)}님에게 폭탄이 넘어갔어요.")
                self._bomb_got(t, None)

    def _bomb_tick(self, now):
        b = self.bomb
        if b:
            if self.phase != "day" or not self.players[b["holder"]].alive:
                self.bomb = None
                self.ai_moves.clear()
            elif now >= b["end"]:
                self._explode(b["holder"])
            else:
                h = b["holder"]
                hb = self.brains.get(h)
                if hb:
                    hb.bomb_step(now)
                for o in self._live_brains():                    # 폭탄이 다가오면 성격대로
                    if o.id != h:
                        o.bomb_near(h, now)
        r_ = self.roulette
        if r_:
            if r_["t0"] is None and now >= r_["auto"]:
                self.spin(r_["who"])
            elif r_["t0"] is not None and now >= r_["t0"] + 4.4:
                self.roulette = None
                self._apply_pen(r_["who"], r_["res"], from_roulette=True)

    def _explode(self, pid):
        self.bomb = None
        self.ai_moves.clear()
        self.version += 1
        kind = self.test.get("penalty") or self.rng.choices([k for k, _ in PENALTY_W], [w for _, w in PENALTY_W])[0]
        if kind == "jail" and self.last_pen.get(pid) == "jail":
            kind = "novote"                                      # 연속 감옥은 투표권 없음으로
        self._event("boom", who=pid, pen=kind)
        self.sys(f"💥 펑! 폭탄이 {self.name(pid)}님에게서 터졌어요!")
        if kind == "roulette":
            self.sys(f"{self.name(pid)} — 🎰 룰렛!")
            self.pen_today[pid] = PEN_SHORT["roulette"]
            res = self.test.get("roulette") or self.rng.choices([k for k, _, _ in ROULETTE], [w for _, _, w in ROULETTE])[0]
            if res == "jail" and self.last_pen.get(pid) == "jail":
                res = "novote"
            human = not self.players[pid].ai
            self.roulette = dict(who=pid, res=res, t0=None, auto=self.now + (5 if human else self.rng.uniform(1.2, 2.2)))
            self.version += 1
            b = self.brains.get(pid)
            if b:
                self.ai_line(pid, "ev_roulette", wait=1.5, q="폭탄이 터져서 룰렛을 돌려야 함")
        else:
            self._apply_pen(pid, kind)
        self._bomb_react(pid, kind)

    def spin(self, pid):
        r_ = self.roulette
        if not r_ or r_["who"] != pid or r_["t0"] is not None:
            return False
        r_["t0"] = self.now
        self.version += 1
        self._event("spin", who=pid, res=r_["res"])
        return True

    def roul_view(self, now):
        r_ = self.roulette
        if not r_:
            return None
        idx = [k for k, _, _ in ROULETTE].index(r_["res"])
        return dict(who=r_["who"], slots=[[k, lab.split(" ", 1)[-1], w, PEN_SHORT[k]] for k, lab, w in ROULETTE],
                    res=idx if r_["t0"] is not None else None,
                    el=round(now - r_["t0"], 2) if r_["t0"] is not None else None,
                    wait=round(max(0, r_["auto"] - now), 1) if r_["t0"] is None else 0)

    def _apply_pen(self, pid, kind, from_roulette=False):
        p = self.players[pid]
        if not p.alive:
            return
        self.last_pen[pid] = kind
        if from_roulette:
            self._event("rres", who=pid, res=kind)
        if kind == "pass":
            self.sys(f"{p.name} — ✅ 통과!")
            self.pen_today[pid] = PEN_SHORT["pass"]
        else:
            self.sys(f"{p.name} — {PEN_LABEL[kind]}")             # 직업과 상관없이 같은 문구
            self.pen_today[pid] = PEN_SHORT[kind]
        if kind == "jail":
            if pid in self.brains:                               # 갇히기 직전 한마디 (그 뒤론 대사 생성 안 함)
                self.post("say", self.pick_text(pid, "ev_jail", dict(x="", d="", y="", z="", t="", r="", v="")), pid, "all")
            self.jailed[pid] = self.day
            self.ready.discard(pid)
            self.votes.pop(pid, None)
            self.ai_moves.pop(pid, None)
            self._event("jail", who=pid)
        elif kind == "novote":
            self.no_vote.add((pid, self.day))
        elif kind == "noability":
            self.no_ability.add((pid, self.day))
        elif kind == "lost":
            if p.role == "마피아":
                self.no_ability.add((pid, self.day))             # 마피아는 제거 능력을 잃지 않음 (오늘 밤만 봉인)
            else:
                self.lost.add(pid)
                self.shield.discard(pid)
        self.version += 1
        if from_roulette:
            self._roulette_react(pid, kind)

    def _bomb_react(self, pid, kind):
        """당사자 반응 + 구경꾼 1~2명 (웃음·위로·놀림)."""
        if kind not in ("roulette", "jail") and pid in self.brains:
            it = {"novote": "ev_novote", "noability": "ev_noability"}[kind]
            self.schedule(self.rng.uniform(.8, 1.6), lambda: self.ai_line(pid, it, wait=1.5,
                                                                            q=f"폭탄이 터져 '{PEN_LABEL[kind]}' 패널티를 받음"))
        self._see_react(pid, f"{self.name(pid)}에게서 폭탄이 터짐 ({PEN_LABEL[kind]})")

    def _roulette_react(self, pid, kind):
        if pid in self.brains:
            it = "ev_rpass" if kind == "pass" else ("ev_rlost" if kind == "lost" else "ev_rother")
            self.schedule(self.rng.uniform(.5, 1.2), lambda: self.ai_line(pid, it, wait=1.5,
                                                                            q=f"룰렛 결과 '{PEN_LABEL[kind]}'"))
        self._see_react(pid, f"{self.name(pid)}의 룰렛 결과: {PEN_LABEL[kind]}", n=1)

    def _see_react(self, pid, what, n=None):
        bs = [b for b in self._live_brains() if b.id != pid and b.id not in self.jailed]
        self.rng.shuffle(bs)
        n = n if n is not None else self.rng.choice([1, 2])
        for i, b in enumerate(bs[:n]):
            side = b.temper.get("side", "none")
            it = {"fuel": "ev_see_laugh", "defend": "ev_see_comfort", "mediate": "ev_see_comfort"}.get(
                side, self.rng.choice(["ev_see_laugh", "ev_see_tease", "ev_see_comfort"]))
            self.schedule(2.2 + i * 1.8 + self.rng.uniform(0, 1),
                          lambda b=b, it=it: self.ai_line(b.id, it, x=pid, wait=1.5, q=what))

    def _release_jail(self):
        for pid in list(self.jailed):
            del self.jailed[pid]
            if self.players[pid].alive:
                self.sys(f"🔓 {self.name(pid)}님이 감옥에서 풀려났어요.")
                self._event("free", who=pid)
        self.pen_today = {}

    def pester_ok(self, h):
        """조용한 사람을 하루 두 번 넘게 찌르지 않기 (자리 비웠을 수도)."""
        return self.pester.get((self.day, h), 0) < 2

    def _dead_air(self, now):
        """토론 중 12초 넘게 아무 말이 없으면 AI 한 명이 먼저 말을 꺼냄."""
        if self.phase != "day" or not self.humans_alive() or self.outq:
            return
        last = max([self.start] + [getattr(self, "_last_say", 0)])
        if now - last < 12 or now - getattr(self, "_last_nudge", 0) < 6:
            return
        bs = [b for b in self.brains.values() if self.players[b.id].alive and b.id not in self.jailed
              and now >= b.sulk_until]                     # 갇히거나 삐진 사람은 정적 깨기 안 함
        bs = [b for b in bs if now - self.ai_last.get(b.id, -99) > 9] or bs
        if bs:
            self._last_nudge = now
            random.choice(bs)._day_line(False)

    def _early(self, now):
        el = now - self.start
        if self.phase == "night":
            return False                       # 밤은 항상 정해진 시간만큼 (일찍 끝나면 누가 능력자인지 티 남)
        if self.phase == "day":
            if self.bomb or self.roulette:
                return False
            hs = [p for p in self.humans_alive() if p.id not in self.jailed]
            return el >= 10 and bool(hs) and all(p.id in self.ready for p in hs)
        if self.phase == "vote":
            return el >= 4 and all(p.id in self.votes for p in self.alive_list()
                                   if p.id not in self.jailed and (p.id, self.day) not in self.no_vote)
        if self.phase == "judge":
            return el >= 3 and all(p.id in self.judge for p in self.alive_list()
                                   if p.id != self.accused and p.id not in self.jailed and (p.id, self.day) not in self.no_vote)
        return False

    def _pump_ai(self, now):
        """AI 말을 사람 대화 속도로 하나씩 내보낸다."""
        q = [o for o in self.outq if o["ph"] == self.phase and o["day"] == self.day
             and now - o["born"] < (20 if o["prio"] == 0 else 14)]
        # 같은 AI 의 잡담이 쌓이면 최신 1개만, 전체 잡담은 3개까지만
        seen, keep = set(), []
        for o in reversed(q):
            if o["prio"] == 1 and o["pid"] in seen:
                continue
            seen.add(o["pid"])
            keep.append(o)
        keep.reverse()
        chat = [o for o in keep if o["prio"] == 1]
        if len(chat) > 3:
            drop = {id(o) for o in chat[:-3]}
            keep = [o for o in keep if id(o) not in drop]
        self.outq = keep
        ready = [o for o in self.outq if o["ready"] <= now]
        if not ready:
            return
        # 사람에게 하는 대답이 제일 먼저, 그다음 해명·꼬리, 감정 반응, 잡담 순
        def rank(o):
            it = o.get("intent") or ""
            to = o.get("to")
            to_h = isinstance(to, tuple) and to[0] in self.players and not self.players[to[0]].ai
            first = it in ("reply",) or it.startswith("ans_") or to_h
            return (o["prio"], 0 if first else (2 if it.startswith("tp_") else 1), o["born"])
        o = min(ready, key=rank)
        # 대답·해명은 1.2초만 띄우면 끼어들 수 있고, 잡담은 정해진 순번(2.5~4초 간격)을 기다림
        if now < (self.ai_post_t + 1.2 if o["prio"] == 0 else self.next_ai_slot):
            return
        self.outq.remove(o)
        silent = now - max(getattr(self, "_last_say", 0), self.start) > 9
        if o["prio"] == 1 and o.get("part", 0) == 0 and not silent:
            if now - self.ai_last.get(o["pid"], -99) < 9:
                return                                          # 같은 AI 잡담은 9초에 한 번
            if self.too_similar(o["text"], o["pid"]):
                return                                          # 방금 나온 말과 비슷하면 버림
        it = o.get("intent") or ""
        if (it == "reply" or it.startswith("ans_")) and o.get("part", 0) == 0:
            la = getattr(self, "_last_ans", None)
            if la and la[0] == o["pid"] and now - la[1] < 5:
                return                                          # 같은 질문에 두 번 대답하지 않게
            self._last_ans = (o["pid"], now)
        self.ai_last[o["pid"]] = now
        self.ai_post_t = now
        # 분위기: 첫날은 탐색이라 느긋하게, 사망 뒤엔 조금 빠르게, 짧은 리액션 뒤엔 바로 다음 말
        mood = 1.25 if self.day <= 1 else (0.9 if any(not p.alive for p in self.players.values()) else 1.0)
        gap = (2.2 + len(o["text"]) * 0.04 + self.rng.uniform(0, 1.6)) * mood
        if len(o["text"]) <= 6:
            gap *= .7
        self.next_ai_slot = now + gap
        self._ai_post(o["pid"], o["text"], o["scope"], o["kind"], o.get("to"))

    def _advance(self, now):
        ph = self.phase
        if ph == "intro":
            self._begin_selfintro(now)
        elif ph == "selfintro":
            self.sys("🗣 자기소개 끝! 이제 소개를 곱씹으며 서로 의심해 보세요.")
            self._begin_day(now)
        elif ph == "night":
            self._resolve_night()
            self._release_jail()
            self._set_phase("morning", now)
        elif ph == "morning":
            if not self._check_win():
                self._begin_day(now)
        elif ph == "day":
            self._begin_vote(now)
        elif ph == "vote":
            if self._resolve_vote():
                self._begin_defense(now)
            else:
                self._set_phase("verdict", now)
        elif ph == "defense":
            self._begin_judge(now)
        elif ph == "judge":
            self._resolve_judge()
            self._set_phase("verdict", now)
        elif ph == "verdict":
            if not self._check_win():
                self._begin_night(now)

    def _can_act(self, p):
        if not p.alive or p.id in self.jailed:
            return False
        if self.phase == "night" and p.id == self.seduced:
            return False
        if self.phase == "night" and (p.id, self.day) in self.no_ability:
            return False                                   # 💣 패널티: 오늘 밤 능력 사용 불가
        if p.id in self.lost and p.role in ("스파이", "마담"):
            return False                                   # 💀 능력 소멸
        if p.role == "기자":
            return not self.reporter_used and self.day >= 2
        return p.role in ("마피아", "의사", "경찰", "스파이")

    def _begin_night(self, now):
        self.night, self.mafia_pick = {}, None
        if self.seduced and self.players[self.seduced].alive:
            self.sys("💋 마담에게 유혹당해 오늘 밤은 능력을 쓸 수 없어요…", to=self.seduced)
        self._set_phase("night", now)
        self.sys(f"🌙 {self.day}번째 밤이 되었습니다. 능력이 있는 사람은 대상을 고르세요.")
        for b in self._live_brains():
            b.on_night()

    def seduce(self, pid, target):
        """마담: 낮(토론·투표)에 한 명 유혹 → 그날 밤 능력 봉인. 하루 한 번."""
        p = self.players.get(pid)
        if (self.phase not in ("day", "vote") or not p or not p.alive or p.role != "마담"
                or self.seduced_by == pid or target not in self.targets(pid)):
            return False
        self.seduced, self.seduced_by = target, pid
        self.version += 1
        self.post("sys", f"💋 {p.name}님이 {self.name(target)}님을 유혹했습니다. 오늘 밤 그 사람은 능력을 못 써요.",
                  scope="mafia")
        return True

    def _begin_day(self, now):
        self.day += 1                                         # 낮이 오면 하루가 시작 (밤 N = 낮 N 다음 밤)
        self.seduced, self.seduced_by = None, None
        self.day_seq = self.seq
        self.ready, self.accused_today = set(), {}
        for k in self.heat:
            self.heat[k] *= 0.6
        self._set_phase("day", now)
        self.sys(f"☀ {self.day}일째 낮. 토론 시간입니다. 다 말했으면 [토론 끝] 을 누르세요.")
        for b in self._live_brains():
            if b.id not in self.jailed:
                b.on_day()
        self._bomb_plan(now)

    def _begin_vote(self, now):
        self.votes = {}
        self._set_phase("vote", now)
        self.sys("🗳 투표 시간! 처형할 사람을 고르세요. (기권 가능)")
        for b in self._live_brains():
            if b.id not in self.jailed:
                b.on_vote()

    def _begin_selfintro(self, now):
        self.intro_order = [p.id for p in self.alive_list()]
        self.rng.shuffle(self.intro_order)
        self.intro_i = -1
        self._set_phase("selfintro", now)
        self.deadline = now + min(self._dur("selfintro"), 4 + 10 * len(self.intro_order))
        self.sys("🙋 사회자: 본격적으로 시작하기 전에, 한 명씩 돌아가며 자기소개 해 볼까요? 이름 불리면 한 줄로!")
        self.schedule(2.5, self._next_intro)

    def _next_intro(self):
        """사회자가 다음 사람을 부름."""
        if self.phase != "selfintro":
            return
        self.intro_i += 1
        self.intro_tok += 1
        tok = self.intro_tok
        if self.intro_i >= len(self.intro_order):
            self.intro_cur = None
            self.deadline = min(self.deadline, self.now + 2)
            return
        pid = self.intro_order[self.intro_i]
        self.intro_cur = pid
        p = self.players[pid]
        self.sys(f"👉 {p.name}님, 자기소개 부탁해요!")
        if p.ai:
            self.schedule(self.rng.uniform(1.2, 2.2), lambda: self.phase == "selfintro" and self.ai_line(pid, "self_intro"))
            self.schedule(6.5, lambda: self.intro_tok == tok and self._after_intro(pid))
        else:
            self.schedule(12, lambda: self.intro_tok == tok and self._intro_timeout(pid))
        self.version += 1

    def _intro_timeout(self, pid):
        if self.phase == "selfintro":
            self.sys(f"⏱ {self.name(pid)}님은 수줍음이 많으시네요~ 다음 분!")
            self._next_intro()

    def _after_intro(self, pid):
        """소개가 끝나면 가끔 AI 하나가 살짝 의심 → 다음 사람."""
        if self.phase != "selfintro":
            return
        p = self.players[pid]
        react = [b for b in self._live_brains() if b.id != pid]
        if react and self.rng.random() < (0.5 if not p.ai else 0.25):
            b = self.rng.choice(react)
            self.ai_line(b.id, "intro_react", x=pid)
            self.schedule(3.5, self._next_intro)
        else:
            self.schedule(0.8, self._next_intro)

    def _begin_defense(self, now):
        self._set_phase("defense", now)
        self.sys(f"🎤 {self.name(self.accused)}님의 최후 변론! ({int(self._dur('defense'))}초) — 이 시간엔 지목된 사람만 말할 수 있어요.")
        for b in self._live_brains():
            b.on_defense()

    def _begin_judge(self, now):
        self.judge = {}
        self._set_phase("judge", now)
        self.sys(f"👍👎 {self.name(self.accused)}님을 처형할까요? 찬성 / 반대를 눌러 주세요.")
        for b in self._live_brains():
            b.on_judge()

    def _resolve_judge(self):
        yes = sum(1 for v in self.judge.values() if v)
        no = sum(1 for v in self.judge.values() if v is False)
        t = self.accused
        ys = ", ".join(self.name(i) for i, v in self.judge.items() if v)
        ns = ", ".join(self.name(i) for i, v in self.judge.items() if v is False)
        self.sys(f"📊 찬반 결과: 찬성 {yes}" + (f"({ys})" if ys else "") + f" · 반대 {no}" + (f"({ns})" if ns else ""))
        if yes > no and self.players[t].role == "정치인" and t not in self.lost:
            self.players[t].revealed = True
            self.sys(f"🏛 {self.name(t)}님은 정치인이라 투표로 처형되지 않습니다!")
            for b in self.brains.values():
                b.on_public_role(t)
        elif yes > no:
            self._kill(t, "vote")
        else:
            self.sys(f"🙏 {self.name(t)}님이 살아남았습니다!")
            for b in self.brains.values():
                b.on_spared(t)
        self.accused = None

    def _live_brains(self):
        return [self.brains[p.id] for p in self.alive_list() if p.id in self.brains]

    def _kill(self, pid, why):
        p = self.players[pid]
        p.alive = False
        p._died, p._cause = self.day, why
        if self.reveal_on_death:
            p.revealed = True
        role = f" (직업: {p.role})" if self.reveal_on_death else ""
        if why == "mafia":
            self.sys(f"💀 밤사이 {p.name}님이 마피아에게 당했습니다.{role}")
        else:
            self.sys(f"⚖ {p.name}님이 투표로 처형되었습니다.{role}")
        if not p.ai:
            self.sys("당신은 죽었습니다. 이제부터 관전하며 죽은 사람끼리만 대화할 수 있어요.", to=pid)
        for b in self.brains.values():
            b.on_death(pid, why)

    def _resolve_night(self):
        kill = self.mafia_pick if any(p.role == "마피아" for p in self.alive_list()) else None
        heals = {t for i, t in self.night.items() if self.players[i].role == "의사" and t}
        if kill and kill in heals:
            self.sys(f"💉 {self.name(kill)}님이 마피아의 공격을 받았지만 의사의 치료로 살아났습니다!")
            kill = None
        elif kill and kill in self.shield and kill not in self.lost:
            self.shield.discard(kill)
            kp = self.players[kill]
            kp.revealed = True
            self.sys(f"🪖 {kp.name}님이 마피아의 공격을 버텨 냈습니다! {kp.name}님은 군인입니다.")
            for b in self.brains.values():
                b.on_public_role(kill)
            kill = None
        elif kill:
            self._kill(kill, "mafia")
        else:
            self.sys("🌅 조용한 밤이었습니다. 아무도 죽지 않았어요.")
        for i, t in self.night.items():
            p = self.players[i]
            if not p.alive or not t:
                continue
            tp = self.players[t]
            if p.role == "경찰":
                res = "마피아" if tp.role == "마피아" else "마피아 아님"
                self.knowledge[i][t] = res
                self.sys(f"🚓 조사 결과: {tp.name}님은 [{res}] 입니다.", to=i)
            elif p.role == "스파이":
                self.knowledge[i][t] = tp.role
                self.sys(f"🕶 정보 입수: {tp.name}님의 직업은 [{tp.role}] 입니다.", to=i)
                if tp.role == "마피아" and not self.spy_contact:
                    self.spy_contact = True
                    for m in self.players.values():
                        if m.role == "마피아":
                            self.knowledge[i][m.id] = "마피아"
                            self.knowledge[m.id][i] = "스파이"
                    self.post("sys", f"🤝 스파이 {p.name}님이 마피아와 접선했습니다! 이제 마피아 채팅에 함께해요.", scope="mafia")
            elif p.role == "기자":
                self.reporter_used = True
                tp.revealed = True
                self.sys(f"📰 특종! 기자의 취재 결과 {tp.name}님의 직업은 [{tp.role}] 입니다!")
                for b in self.brains.values():
                    b.on_public_role(t)
        for b in self._live_brains():
            b.on_morning()

    def _resolve_vote(self):
        tally = {}
        for v, t in self.votes.items():
            if t:
                tally[t] = tally.get(t, 0) + self.vote_weight(v)
        if not tally:
            self.sys("모두 기권했습니다. 아무도 처형되지 않았어요.")
            return False
        top = max(tally.values())
        best = [t for t, c in tally.items() if c == top]
        voters = {}
        for v, t in self.votes.items():
            voters.setdefault(t, []).append(self.name(v) + ("×2" if self.vote_weight(v) == 2 and t else ""))
            self.vote_log.append((self.day, v, t))
            if t:
                self.heat[t] += .15
            for b in self._live_brains():
                b.on_vote_cast(v, t)
        summary = " / ".join(f"{self.name(t)} {c}표({', '.join(voters[t])})"
                             for t, c in sorted(tally.items(), key=lambda x: -x[1]))
        abst = voters.get(None, [])
        self.sys(f"📊 투표 결과: {summary}" + (f" / 기권: {', '.join(abst)}" if abst else ""))
        if len(best) > 1:
            self.sys("동점이라 아무도 처형되지 않았습니다.")
            return False
        self.accused = best[0]
        return True

    def vote_weight(self, pid):
        return 2 if self.players[pid].role == "정치인" and pid not in self.lost else 1

    def _check_win(self):
        alive = self.alive_list()
        mafia = sum(p.role == "마피아" for p in alive)
        team = sum(p.role in MAFIA_TEAM for p in alive)
        if mafia == 0:
            self.winner = "시민"
        elif team >= len(alive) - team:
            self.winner = "마피아"
        if not self.winner:
            return False
        self.phase, self.deadline = "end", self.now
        self.version += 1
